function makeTask(
  id: string, phase: TaskPhase, title: string, why_it_matters: string, owner: TaskOwner,
  classification: TaskClassification, opts?: { resource?: TaskResource; contact_for_help?: string; blocks_readiness?: boolean },
): ContractorTask {
  return {
    id, phase, title, why_it_matters, owner,
    classification, conditional: classification !== 'core',
    status: 'NOT_STARTED',
    depends_on: [],
    due_date: null,
    notes: '',
    blocked_reason: null,
    history: [],
    resource: opts?.resource ?? null,
    contact_for_help: opts?.contact_for_help ?? '',
    blocks_readiness: opts?.blocks_readiness ?? true,
  };
}

const RESOURCES = {
  niitTraining: { label: 'NIIT Mandatory Training Hub', url: 'https://learning.niit.com/mandatory-training' } as TaskResource,
  casInduction: { label: 'CAS Induction Pack', url: 'https://cas.niit.com/induction' } as TaskResource,
};
// Per the brief: never fabricate a resource that hasn't been validated.
// Anything not explicitly confirmed stays null -> "Resource to be confirmed".
const UNCONFIRMED: TaskResource = null;

// ── Core tasks — always generated regardless of requirements ──
export function generateCoreTasks(opts?: { projectLeadKnown?: boolean }): ContractorTask[] {
  const tasks: ContractorTask[] = [];

  tasks.push(makeTask('C1', 'clearance', 'Confirm engagement / SOW', 'The engagement agreement is the legal basis for everything that follows — nothing else can be relied on until it\'s signed.', 'resourcing', 'core'));

  if (!opts?.projectLeadKnown) {
    tasks.push(makeTask('K0', 'kickoff', 'Assign or confirm Project Lead', 'The Project Lead owns day-to-day direction — kickoff can\'t be scheduled meaningfully without one.', 'resourcing', 'core'));
  }
  tasks.push(makeTask('K1', 'kickoff', 'Schedule project kickoff', 'Kickoff is where the working relationship actually starts — it should happen as close to day one as possible.', 'project', 'core'));
  tasks.push(makeTask('K2', 'kickoff', 'Explain project scope and ways of working', 'Avoids early misunderstandings about what\'s in scope and how the team actually works day to day.', 'project', 'core'));
  tasks.push(makeTask('K3', 'kickoff', 'Assign initial project tasks', 'Gives the person real work to start on immediately after kickoff, rather than a gap at the start.', 'project', 'core'));

  tasks.push(makeTask('T1', 'kickoff', 'Complete applicable NIIT mandatory training', 'NIIT requires baseline training for anyone working under its name, regardless of engagement type.', 'contractor', 'core', { resource: RESOURCES.niitTraining }));
  tasks.push(makeTask('T2', 'kickoff', 'Complete CAS induction', 'CAS induction covers how this specific practice operates — not covered by general NIIT training.', 'contractor', 'core', { resource: RESOURCES.casInduction }));

  tasks.push(makeTask('K4', 'kickoff', 'Confirm key contacts', 'Makes sure the person knows who to go to for access issues, project questions, and billing — before they need to ask.', 'resourcing', 'core'));
  tasks.push(makeTask('B0', 'billing', 'Confirm missing billing information (verification method, billing cadence, Delivery Manager)', 'These details are rarely known at engagement creation — this is where they get captured instead of blocking the record.', 'resourcing', 'core'));
  tasks.push(makeTask('R1', 'billing', 'Confirm readiness', 'The final checkpoint before the engagement is marked Ready to start — a deliberate human confirmation, not just the computed gates.', 'resourcing', 'core'));

  return tasks;
}

// Only added when the matching requirement is Yes (the real task) or Unsure
// (a confirmation task — never silently dropped). Never asked about
// individually beyond the Step 2 answers.
export function generateConditionalTasks(req: ContractorRequirements): ContractorTask[] {
  const tasks: ContractorTask[] = [];

  const add = (
    answer: RequirementAnswer, realId: string, phase: TaskPhase, realTitle: string, why: string, owner: TaskOwner,
    opts?: { resource?: TaskResource; blocks_readiness?: boolean; confirmBlocksReadiness?: boolean },
  ) => {
    if (answer === 'yes') {
      tasks.push(makeTask(realId, phase, realTitle, why, owner, 'conditional', { resource: opts?.resource, blocks_readiness: opts?.blocks_readiness }));
    } else if (answer === 'unsure') {
      tasks.push(makeTask(`${realId}_CONF`, phase, `Confirm requirement: ${realTitle}`, 'This was left as "to be confirmed" at creation — NAYA never assumes it away, so it stays open until someone resolves it.', 'resourcing', 'conditional', { blocks_readiness: opts?.confirmBlocksReadiness ?? opts?.blocks_readiness ?? true }));
    }
  };

  // Contract & Compliance
  if (req.nda === 'yes') {
    tasks.push(makeTask('C2', 'clearance', 'Send NDA', 'An NDA protects both sides before any confidential project information is shared.', 'resourcing', 'conditional'));
    tasks.push(makeTask('C3', 'clearance', 'Sign NDA', 'The contractor\'s own signature is what makes the NDA enforceable.', 'contractor', 'conditional'));
  } else if (req.nda === 'unsure') {
    tasks.push(makeTask('C2_CONF', 'clearance', 'Confirm requirement: NDA', 'Left as "to be confirmed" — NAYA never assumes it away.', 'resourcing', 'conditional'));
  }
  add(req.background_check, 'CC1', 'clearance', 'Complete background / compliance check', 'Required before the person can be given any real access or responsibility on the engagement.', 'legal_compliance');
  add(req.insurance, 'INS1', 'clearance', 'Provide insurance evidence', 'Confirms the contractor carries the cover the engagement requires before work begins.', 'contractor');
  add(req.hr_legal_review, 'HRL1', 'clearance', 'HR / Legal classification review', 'Confirms the engagement is classified and structured correctly before it proceeds.', 'legal_compliance');

  // Systems & Access
  add(req.niit_account, 'A1', 'access', 'Create NIIT email / account', 'Needed before almost anything else — most other systems key off this account.', 'resourcing', { blocks_readiness: true });
  add(req.hardware, 'HW1', 'access', 'Arrange NIIT hardware', 'The person can\'t do NIIT-side work without NIIT-issued equipment.', 'it_client_admin', { blocks_readiness: true });
  add(req.client_access, 'CA1', 'access', 'Request client system access', 'Needed to actually work in the client\'s environment.', 'it_client_admin', {
    blocks_readiness: req.client_access_policy !== 'can_follow_induction',
    confirmBlocksReadiness: req.client_access_policy !== 'can_follow_induction',
  });
  add(req.client_badge, 'CB1', 'access', 'Arrange client badge / physical access', 'Needed for any on-site presence at the client.', 'it_client_admin');

  // Induction & Training (NIIT training / CAS induction are core — see generateCoreTasks)
  add(req.client_training, 'CT1', 'kickoff', 'Complete client-required training', 'Some clients require their own training before anyone can start on their systems or site.', 'contractor', {
    resource: UNCONFIRMED,
    blocks_readiness: req.client_training_policy !== 'can_follow_induction',
    confirmBlocksReadiness: req.client_training_policy !== 'can_follow_induction',
  });
  add(req.project_training, 'PT1', 'kickoff', 'Complete project-specific training', 'Covers tools or processes specific to this project that general induction doesn\'t.', 'contractor', { resource: UNCONFIRMED });

  // Time & Billing
  if (req.time_tracking === 'yes') {
    tasks.push(makeTask('TT1', 'billing', 'Set up time-tracking codes', 'Required before any time can be logged correctly.', 'resourcing', 'conditional'));
    tasks.push(makeTask('TT2', 'billing', 'Brief contractor on time entry', 'Avoids incorrectly logged time in the first week.', 'resourcing', 'conditional'));
  } else if (req.time_tracking === 'unsure') {
    tasks.push(makeTask('TT1_CONF', 'billing', 'Confirm requirement: Time tracking', 'Left as "to be confirmed" — NAYA never assumes it away.', 'resourcing', 'conditional'));
  }
  add(req.invoicing, 'INV1', 'billing', 'Confirm invoicing process', 'Needed before the first invoice can be submitted correctly.', 'delivery');

  return tasks;
}

// Only the dependencies the spec actually calls for — not a blanket
// "depends on the whole previous phase." Applied by id, so it's a no-op for
// any task that wasn't generated (an excluded requirement never creates a
// task, so it can never appear as a dependency either).
function assignDependencies(tasks: ContractorTask[]): ContractorTask[] {
  const byId = new Map(tasks.map(t => [t.id, t]));
  const has = (id: string) => byId.has(id);
  const setDeps = (id: string, deps: string[]) => {
    const t = byId.get(id);
    if (t) t.depends_on = deps.filter(has);
  };

  // Systems/access tasks depend on the agreement being confirmed.
  ['A1', 'HW1', 'CA1', 'CB1'].forEach(id => setDeps(id, ['C1']));

  // Project kickoff depends on the Project Lead being confirmed (only
  // meaningful if K0 exists — otherwise the Lead was already known).
  if (has('K0')) setDeps('K1', ['K0']);

  // Initial task assignment depends on kickoff having happened.
  setDeps('K3', ['K1']);

  // First time-entry readiness depends on time-tracking setup.
  if (has('TT1')) setDeps('TT2', ['TT1']);

  // Readiness confirmation depends on training/induction and billing basics.
  setDeps('R1', ['T1', 'T2', 'B0'].filter(has));

  return tasks;
}

export function generateContractorTasks(req: ContractorRequirements, opts?: { projectLeadKnown?: boolean }): ContractorTask[] {
  const all = [...generateCoreTasks(opts), ...generateConditionalTasks(req)];
  return assignDependencies(all);
}

export function countCoreTasks(opts?: { projectLeadKnown?: boolean }): number {
  return generateCoreTasks(opts).length;
}

export function countConditionalTasks(req: ContractorRequirements): number {
  return generateConditionalTasks(req).length;
}

export function taskProgress(tasks: ContractorTask[]): { done: number; total: number; pct: number } {
  const applicable = tasks.filter(t => t.status !== 'NOT_APPLICABLE');
  const done = applicable.filter(t => t.status === 'COMPLETE').length;
  const total = applicable.length || 1;
  return { done, total, pct: Math.round((done / total) * 100) };
}

// A phase "clears" when every applicable, readiness-blocking task in it is
// COMPLETE. An empty/all-N/A/non-blocking phase counts as cleared. This is
// also what makes excluded requirements harmless for readiness: a task that
// was never generated simply isn't part of any phase's gate, and a task
// explicitly marked non-blocking (e.g. client access that "can follow
// induction") is tracked but doesn't hold up readiness.
export function phaseGate(tasks: ContractorTask[], phase: TaskPhase): boolean {
  const applicable = tasks.filter(t => t.phase === phase && t.status !== 'NOT_APPLICABLE' && t.blocks_readiness !== false);
  return applicable.every(t => t.status === 'COMPLETE');
}

export function readinessGates(tasks: ContractorTask[]): Record<TaskPhase, boolean> {
  return {
    clearance: phaseGate(tasks, 'clearance'),
    access: phaseGate(tasks, 'access'),
    kickoff: phaseGate(tasks, 'kickoff'),
    billing: phaseGate(tasks, 'billing'),
  };
}

// Computed, never stored, never manually ticked — always derived fresh from
// the four gates so it can't drift from the underlying task states.
export function isReadyToStart(tasks: ContractorTask[]): boolean {
  const g = readinessGates(tasks);
  return g.clearance && g.access && g.kickoff && g.billing;
}

// A task can move to COMPLETE only once everything it depends on is COMPLETE
// or NOT_APPLICABLE. Returns the blocking task titles, if any.
export function blockingDependencies(tasks: ContractorTask[], task: ContractorTask): ContractorTask[] {
  if (!task.depends_on.length) return [];
  const byId = new Map(tasks.map(t => [t.id, t]));
  return task.depends_on
    .map(id => byId.get(id))
    .filter((t): t is ContractorTask => !!t && t.status !== 'COMPLETE' && t.status !== 'NOT_APPLICABLE');
}

// Defensive server-side check — the task graph is always engine-generated
// today, never user-editable, but this guards against a future change (or a
// hand-crafted API request) introducing a dependency on a task that doesn't
// exist, or a dependency cycle that would make a task permanently
// uncompletable.
export function validateTaskGraph(tasks: ContractorTask[]): string | null {
  const ids = new Set(tasks.map(t => t.id));
  for (const t of tasks) {
    for (const dep of t.depends_on) {
      if (!ids.has(dep)) return `Task "${t.id}" depends on unknown task "${dep}"`;
    }
  }
  const WHITE = 0, GRAY = 1, BLACK = 2;
  const color = new Map<string, number>();
  const byId = new Map(tasks.map(t => [t.id, t]));
  const visit = (id: string): string | null => {
    color.set(id, GRAY);
    const task = byId.get(id);
    for (const dep of task?.depends_on || []) {
      const c = color.get(dep) ?? WHITE;
      if (c === GRAY) return `Circular dependency involving "${id}" and "${dep}"`;
      if (c === WHITE) {
        const err = visit(dep);
        if (err) return err;
      }
    }
    color.set(id, BLACK);
    return null;
  };
  for (const id of Array.from(ids)) {
    if ((color.get(id) ?? WHITE) === WHITE) {
      const err = visit(id);
      if (err) return err;
    }
  }
  return null;
}

