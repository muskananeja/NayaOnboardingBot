// ═══════════════════════════════════════════════════════════════
// Contractor & Associate onboarding — task generation engine
//
// Design: the Resourcing Lead creates a record by answering a small set of
// inputs (who, when, who owns it, what's required). NAYA derives the full
// task list from those inputs — the contractor/associate never configures
// their own onboarding, and the creator never hand-builds a checklist.
// This file is the single source of truth for that derivation, used by both
// the creation API and the dashboard/contractor-facing views.
//
// `engagement_type` distinguishes Contractor from Associate on top of the
// SAME engine — there is deliberately no second task engine. Everything
// else (phases, dependencies, readiness) is shared.
// ═══════════════════════════════════════════════════════════════

export type TaskOwner = 'resourcing' | 'project' | 'delivery' | 'contractor' | 'it_client_admin' | 'legal_compliance';
export type TaskStatus =
  | 'NOT_STARTED'
  | 'IN_PROGRESS'
  | 'WAITING_ON_CONTRACTOR'
  | 'WAITING_ON_INTERNAL'
  | 'WAITING_ON_CLIENT'
  | 'COMPLETE'
  | 'NOT_APPLICABLE'
  | 'BLOCKED';
export type TaskPhase = 'clearance' | 'access' | 'kickoff' | 'billing';
export type EngagementType = 'contractor' | 'associate';

// Georgie's four-value classification — descriptive metadata on each task,
// not a second status field. "Core" = always generated. "Conditional" =
// generated when the matching requirement is Yes or Unsure. "Custom" =
// reserved for a future hand-added task (not generated by this engine
// today). "Not applicable" = a conditional task whose requirement was
// answered No, so it was never generated at all.
export type TaskClassification = 'core' | 'conditional' | 'custom';

export type TaskHistoryEntry = {
  previous_status: TaskStatus | null;
  new_status: TaskStatus;
  updated_by: string; // 'admin' | 'contractor' — single shared admin role until real per-person identity exists
  updated_at: number;
  note?: string;
};

export type TaskResource = { label: string; url: string } | null;

export type ContractorTask = {
  id: string;
  phase: TaskPhase;
  title: string;
  why_it_matters: string;
  owner: TaskOwner;
  classification: TaskClassification;
  conditional: boolean; // kept for backward compatibility with existing records/UI — equivalent to classification !== 'core'
  status: TaskStatus;
  depends_on: string[]; // task ids that must be COMPLETE or NOT_APPLICABLE before this one can be COMPLETE
  due_date: string | null;
  notes: string;
  blocked_reason: string | null;
  history: TaskHistoryEntry[];
  resource: TaskResource; // null renders as "Resource to be confirmed" — never a fabricated link
  contact_for_help: string; // free text, e.g. a role name — '' if not set
  blocks_readiness: boolean; // almost always true; false only for a requirement explicitly marked as not blocking (e.g. client access that "can follow induction")
};

export type RequirementAnswer = 'yes' | 'no' | 'unsure';
export type VerificationMethod = 'hours' | 'deliverables';
export type BillingCadence = 'weekly' | 'monthly' | 'milestone';
export type AccessPolicy = 'required_before_start' | 'can_follow_induction';

export type ContractorRequirements = {
  // Contract & compliance
  nda: RequirementAnswer;
  background_check: RequirementAnswer; // "Background or compliance review"
  insurance: RequirementAnswer;
  hr_legal_review: RequirementAnswer;
  // Systems & access
  niit_account: RequirementAnswer;
  hardware: RequirementAnswer;
  client_access: RequirementAnswer;
  client_access_policy: AccessPolicy; // only meaningful when client_access is yes/unsure — NAYA never invents this, the admin sets it
  client_badge: RequirementAnswer;
  // Induction & training (NIIT training + CAS induction are core, not asked here)
  client_training: RequirementAnswer;
  client_training_policy: AccessPolicy;
  project_training: RequirementAnswer;
  // Time & billing
  time_tracking: RequirementAnswer;
  invoicing: RequirementAnswer;
  // Deferred to a later task by default — not asked at creation.
  verification_method: VerificationMethod | null;
  billing_cadence: BillingCadence | null;
};

export type ContractorRecord = {
  journey_type: 'contractor';
  engagement_type: EngagementType;
  country_of_work: string;
  invite_token_hash?: string; // one-way lookup key only — never the raw token, which is shown once at issue/regenerate and never persisted
  invite_expires_at?: number;
  contractor_id: string;
  contractor_name: string;
  contractor_email: string;
  project_name: string;
  client: string; // free text, or 'Internal / no external client'
  start_date: string; // ISO date (yyyy-mm-dd)
  end_date: string; // '' unless the engagement is fixed-term
  resourcing_lead: string;
  project_lead: string; // '' until confirmed — moved to a later task if not known at creation
  delivery_manager: string; // '' until set — moved to a later task
  requirements: ContractorRequirements;
  tasks: ContractorTask[];
  created_at: number;
  last_saved: number;
};

