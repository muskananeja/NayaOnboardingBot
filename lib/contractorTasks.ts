// Brings an older record (earlier status values, boolean requirements, a
// missing engagement_type, missing task fields) up to the current display
// shape. Applied in-memory wherever a record is read — never a bulk job
// against KV. A record is only re-persisted in this shape the next time
// something on it is actually updated, and its EXISTING tasks are never
// regenerated or altered here — only normalized so every field the UI
// expects is present.
export function migrateContractorRecord(record: any): ContractorRecord {
  const STATUS_MAP: Record<string, TaskStatus> = { PENDING: 'NOT_STARTED' };
  const tasks: ContractorTask[] = (record.tasks || [])
    // The old "Ready to start — final sign-off" task is obsolete now that
    // readiness is computed — drop it from view rather than leave a dead
    // manually-clickable task sitting in the billing phase.
    .filter((t: any) => !(t.id === 'B5' && /ready to start/i.test(t.title || '')))
    .map((t: any) => ({
      id: t.id,
      phase: t.phase,
      title: t.title,
      why_it_matters: t.why_it_matters || '',
      owner: t.owner,
      classification: t.classification || (t.conditional ? 'conditional' : 'core'),
      conditional: !!t.conditional,
      status: STATUS_MAP[t.status] || t.status || 'NOT_STARTED',
      depends_on: Array.isArray(t.depends_on) ? t.depends_on : [],
      due_date: t.due_date ?? null,
      notes: t.notes ?? '',
      blocked_reason: t.blocked_reason ?? null,
      history: Array.isArray(t.history) ? t.history : [],
      resource: t.resource ?? null,
      contact_for_help: t.contact_for_help ?? '',
      blocks_readiness: t.blocks_readiness !== false,
    }));
  const r = record.requirements || {};
  const toAnswer = (legacyBool: any, current: any): RequirementAnswer =>
    current === 'yes' || current === 'no' || current === 'unsure' ? current : (legacyBool ? 'yes' : 'no');
  return {
    journey_type: 'contractor',
    engagement_type: record.engagement_type === 'associate' ? 'associate' : 'contractor',
    country_of_work: record.country_of_work || '',
    invite_token_hash: record.invite_token_hash,
    invite_expires_at: record.invite_expires_at,
    contractor_id: record.contractor_id,
    contractor_name: record.contractor_name,
    contractor_email: record.contractor_email,
    project_name: record.project_name,
    client: record.client,
    start_date: record.start_date || '',
    end_date: record.end_date || '',
    resourcing_lead: record.resourcing_lead || '',
    project_lead: record.project_lead || '',
    delivery_manager: record.delivery_manager || '',
    requirements: {
      nda: toAnswer(r.nda, r.nda),
      background_check: toAnswer(r.client_compliance, r.background_check),
      insurance: toAnswer(r.insurance, r.insurance),
      hr_legal_review: toAnswer(false, r.hr_legal_review),
      niit_account: toAnswer(r.niit_account, r.niit_account),
      hardware: toAnswer(r.hardware, r.hardware),
      client_access: toAnswer(r.client_access, r.client_access),
      client_access_policy: r.client_access_policy === 'can_follow_induction' ? 'can_follow_induction' : 'required_before_start',
      client_badge: toAnswer(r.client_badge, r.client_badge),
      client_training: toAnswer(false, r.client_training),
      client_training_policy: r.client_training_policy === 'can_follow_induction' ? 'can_follow_induction' : 'required_before_start',
      project_training: toAnswer(false, r.project_training),
      time_tracking: toAnswer(r.time_tracking, r.time_tracking),
      invoicing: toAnswer(r.invoicing, r.invoicing),
      verification_method: r.verification_method ?? null,
      billing_cadence: r.billing_cadence ?? null,
    },
    tasks,
    created_at: record.created_at || record.last_saved || Date.now(),
    last_saved: record.last_saved || Date.now(),
  };
}
